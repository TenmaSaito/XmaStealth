//==================================================================================
//**********************************************************************************
// *** インクルードファイル ***
//**********************************************************************************
#include "cameraRanking.h"

//**********************************************************************************
// *** グローバル変数 ***
//**********************************************************************************
static CameraRanking g_cameraRanking;		// カメラの情報

//==================================================================================
// --- カメラの初期化 ---
//==================================================================================
void InitCameraRanking(void)
{
	InitCameraInfo(&g_cameraRanking);
}

//==================================================================================
// --- カメラの終了 ---
//==================================================================================
void UninitCameraRanking(void)
{

}

//==================================================================================
// --- カメラの更新 (注視点の周りを回転) ---
//==================================================================================
void UpdateCameraRanking(void)
{
	CameraRanking *pCamera = &g_cameraRanking;		// カメラの情報

	pCamera->rot.y = RepairRot(pCamera->rot.y - pCamera->fRotSpd);

	/*** 角度から視点位置を算出 ***/
	pCamera->posV.x = pCamera->posR.x + sinf(pCamera->rot.y) * pCamera->fZLength;
	pCamera->posV.z = pCamera->posR.z + cosf(pCamera->rot.y) * pCamera->fZLength;
}

//==================================================================================
// --- カメラの設置 (プロジェクション・ビューマトリックスの設定) ---
//==================================================================================
void SetCameraRanking(void)
{
	SetCameraTransform(&g_cameraRanking);
}

//==================================================================================
// --- カメラの情報の設定 ---
//==================================================================================
void SetCameraRanking(D3DXVECTOR3 posV, D3DXVECTOR3 posR, float fAngle, float fZNear, float fZFar, float fZLength, float fSpd, float fRotSpd)
{
	SetCameraInfo(&g_cameraRanking, posV, posR, fAngle, fZNear, fZFar, fZLength, fSpd, fRotSpd);
}

//==================================================================================
// --- カメラの取得 ---
//==================================================================================
CameraRanking *GetCameraRanking(void)
{
	return &g_cameraRanking;
}
