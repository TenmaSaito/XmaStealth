// 注視点を中心に、一定距離を保ちながらY軸回りに自動回転するカメラ。
// 初期化・行列設定は camera.cpp の共通処理を使う。
//
//==================================================================================
//**********************************************************************************
// *** インクルードファイル ***
//**********************************************************************************
#include "cameraTitle.h"

//**********************************************************************************
// *** グローバル変数 ***
//**********************************************************************************
static CameraTitle g_cameraTitle;		// カメラの情報

//==================================================================================
// --- カメラの初期化 ---
//==================================================================================
void InitCameraTitle(void)
{
	InitCameraInfo(&g_cameraTitle);
}

//==================================================================================
// --- カメラの終了 ---
//==================================================================================
void UninitCameraTitle(void)
{

}

//==================================================================================
// --- カメラの更新 (注視点の周りを回転) ---
//==================================================================================
void UpdateCameraTitle(void)
{
	CameraTitle *pCamera = &g_cameraTitle;		// カメラの情報

	if (pCamera->fRotSpd != 0.0f)
	{ // 回転速度が設定されている時だけ回転
		pCamera->rot.y = RepairRot(pCamera->rot.y - pCamera->fRotSpd);

		/*** 角度から視点位置を算出 ***/
		pCamera->posV.x = pCamera->posR.x + sinf(pCamera->rot.y) * pCamera->fZLength;
		pCamera->posV.z = pCamera->posR.z + cosf(pCamera->rot.y) * pCamera->fZLength;
	}
}

//==================================================================================
// --- カメラの設置 (プロジェクション・ビューマトリックスの設定) ---
//==================================================================================
void SetCameraTitle(void)
{
	SetCameraTransform(&g_cameraTitle);
}

//==================================================================================
// --- カメラの情報の設定 ---
//==================================================================================
void SetCameraTitle(D3DXVECTOR3 posV, D3DXVECTOR3 posR, float fAngle, float fZNear, float fZFar, float fZLength, float fSpd, float fRotSpd)
{
	SetCameraInfo(&g_cameraTitle, posV, posR, fAngle, fZNear, fZFar, fZLength, fSpd, fRotSpd);
}

//==================================================================================
// --- カメラの取得 ---
//==================================================================================
CameraTitle *GetCameraTitle(void)
{
	return &g_cameraTitle;
}
