#include "light.h"

//**********************************************************************************
// *** マクロ定義 ***
//**********************************************************************************
#define LIGHT_NUM		(3)			// ライトの数

//**********************************************************************************
// *** グローバル変数 ***
//**********************************************************************************
static D3DLIGHT9 g_aLight[LIGHT_NUM];		// ライトの情報

//==================================================================================
// --- ライトの初期化 ---
//==================================================================================
void InitLight(void)
{
	LPDIRECT3DDEVICE9 pDevice = GetDevice();		// デバイス

	// 各ライトの拡散光 (メイン → 補助の順に暗くする)
	const D3DXCOLOR aDiffuse[LIGHT_NUM] =
	{
		D3DXCOLOR(1.0f, 1.0f, 1.0f, 1.0f),
		D3DXCOLOR(0.7f, 0.7f, 0.7f, 1.0f),
		D3DXCOLOR(0.3f, 0.3f, 0.3f, 1.0f),
	};

	// 各ライトの方向 (正規化前)
	const D3DXVECTOR3 aDirection[LIGHT_NUM] =
	{
		D3DXVECTOR3(0.2f, -0.8f, -0.4f),
		D3DXVECTOR3(-0.3f, 0.7f, 0.5f),
		D3DXVECTOR3(0.0f, -0.5f, 0.5f),
	};

	/*** ライトの情報を初期化 ***/
	ZeroMemory(&g_aLight[0], sizeof g_aLight);

	for (int nCntLight = 0; nCntLight < LIGHT_NUM; nCntLight++)
	{
		D3DXVECTOR3 vecDir = aDirection[nCntLight];		// ライトの方向ベクトル

		/*** 種類・拡散光・方向を設定 ***/
		g_aLight[nCntLight].Type = D3DLIGHT_DIRECTIONAL;
		g_aLight[nCntLight].Diffuse = aDiffuse[nCntLight];
		D3DXVec3Normalize(&vecDir, &vecDir);
		g_aLight[nCntLight].Direction = vecDir;

		/*** ライトを設定して有効にする ***/
		pDevice->SetLight(nCntLight, &g_aLight[nCntLight]);
		pDevice->LightEnable(nCntLight, TRUE);
	}
}

