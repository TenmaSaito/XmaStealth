#include "cameraTutorial.h"
#include "player.h"

//**********************************************************************************
// *** グローバル変数 ***
//**********************************************************************************
static CameraTutorial g_cameraTutorial;		// カメラの情報

//==================================================================================
// --- カメラの初期化 ---
//==================================================================================
void InitCameraTutorial(void)
{
	InitCameraInfo(&g_cameraTutorial);
}

//==================================================================================
// --- カメラの終了 ---
//==================================================================================
void UninitCameraTutorial(void)
{

}

//==================================================================================
// --- カメラの更新 (プレイヤー追従) ---
//==================================================================================
void UpdateCameraTutorial(void)
{
	UpdateFollowCamera(&g_cameraTutorial, false);
}

//==================================================================================
// --- カメラの設置 (プロジェクション・ビューマトリックスの設定) ---
//==================================================================================
void SetCameraTutorial(void)
{
	SetCameraTransform(&g_cameraTutorial);
}

//==================================================================================
// --- カメラの情報の設定 ---
//==================================================================================
void SetCameraTutorial(D3DXVECTOR3 posV, D3DXVECTOR3 posR, float fAngle, float fZNear, float fZFar, float fZLength, float fSpd, float fRotSpd)
{
	SetCameraInfo(&g_cameraTutorial, posV, posR, fAngle, fZNear, fZFar, fZLength, fSpd, fRotSpd);
}

//==================================================================================
// --- カメラの取得 ---
//==================================================================================
CameraTutorial *GetCameraTutorial(void)
{
	return &g_cameraTutorial;
}

//==================================================================================
// --- カメラの向き・距離のリセット ---
//==================================================================================
void ResetCameraTutorial(void)
{
	ResetCameraInfo(&g_cameraTutorial);
}
