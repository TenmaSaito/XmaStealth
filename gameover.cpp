#include "gameover.h"
#include "gameoverBg.h"
#include "fade.h"

//**********************************************************************************
// *** マクロ定義 ***
//**********************************************************************************
#define GAMEOVER_FADE_TIME		(120)		// ランキング画面へのフェード時間(フレーム)
#define GAMEOVER_AUTO_FRAME		(1)			// 自動でランキング画面へ遷移し始めるフレーム

//**********************************************************************************
// *** グローバル変数 ***
//**********************************************************************************
static int g_nCounterGameOver;		// ゲームオーバー画面の経過フレーム

//==================================================================================
// --- ゲームオーバー画面の初期化 ---
//==================================================================================
void InitGameOver(void)
{
	g_nCounterGameOver = 0;

	/*** 背景の初期化 ***/
	InitGameOverBg();
}

//==================================================================================
// --- ゲームオーバー画面の終了 ---
//==================================================================================
void UninitGameOver(void)
{
	/*** 背景の終了 ***/
	UninitGameOverBg();
}

//==================================================================================
// --- ゲームオーバー画面の更新 ---
//==================================================================================
void UpdateGameOver(void)
{
	/*** 背景の更新 ***/
	UpdateGameOverBg();

	if ((GetKeyboardTrigger(DIK_RETURN)
		|| GetJoypadTrigger(JOYKEY_A)
		|| GetJoypadTrigger(JOYKEY_START))
		&& GetFade() == FADE_NONE)
	{ // 決定入力でランキング画面へ
		PlaySound(SOUND_LABEL_SE_ENTER);

		SetFade(MODE_RANKING, FADE_TYPE_NORMAL, GAMEOVER_FADE_TIME);
	}

	if (g_nCounterGameOver >= GAMEOVER_AUTO_FRAME && GetFade() == FADE_NONE)
	{ // 一定時間経過で自動的にランキング画面へ
		SetFade(MODE_RANKING, FADE_TYPE_NORMAL, GAMEOVER_FADE_TIME);
	}

	/*** デバッグ表示 : マウス座標 ***/
	PrintDebugProc("MOUSE x/y %~2f\n", (float)GetMousePos().x, (float)GetMousePos().y);

	g_nCounterGameOver++;
}

//==================================================================================
// --- ゲームオーバー画面の描画 ---
//==================================================================================
void DrawGameOver(void)
{
	/*** 背景の描画 ***/
	DrawGameOverBg();
}
